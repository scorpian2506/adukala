// Regenerates src/data/recipes/index.ts from every recipe file in the folder.
//   node scripts/gen-recipe-index.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "src/data/recipes";
// Order of sections on screen: the original library first, then by cuisine.
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/^[0-9]/, "_$&");
const imports = [];
const names = [];
for (const f of files) {
  const src = readFileSync(join(dir, f), "utf8");
  const base = f.replace(/\.ts$/, "");
  const named = src.match(/export const (\w+): Recipe/);
  if (named) {
    imports.push(`import { ${named[1]} } from "./${base}";`);
    names.push(named[1]);
  } else if (/export default/.test(src)) {
    const n = camel(base);
    imports.push(`import ${n} from "./${base}";`);
    names.push(n);
  } else {
    throw new Error(`${f}: no Recipe export found`);
  }
}

const out = `// Generated by scripts/gen-recipe-index.mjs — do not edit by hand.
import type { Recipe } from "../../lib/types";
${imports.join("\n")}

export const SEED_RECIPES: Recipe[] = [
${names.map((n) => `  ${n},`).join("\n")}
];
`;
writeFileSync(join(dir, "index.ts"), out);
console.log(`index.ts: ${names.length} recipes`);
